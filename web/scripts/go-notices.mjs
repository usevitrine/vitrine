// Writes internal/server/licenses/go.txt: the license texts of everything compiled into the vitrine binary - Go's
// standard library and each module `go list -deps` finds for ./cmd/vitrine - and of the icons adapted from Feather.
// Their licenses (MIT, BSD, Apache-2.0) ask that their notices travel with the program; the server shows them at
// /licenses with the web app's own (Vite's build.license). Run after changing Go dependencies: `npm run notices`.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const go = (...args) => execFileSync('go', args, { cwd: root, encoding: 'utf8' });

const lines = go('list', '-deps', '-f', '{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}', './cmd/vitrine')
  .split('\n')
  .filter(Boolean);
const modules = [...new Map(lines.map((l) => [l.split('\t')[0], l.split('\t')])).values()].sort((a, b) => a[0].localeCompare(b[0]));

// (LICENSE, LICENSE.md, LICENSE-2.0.txt, LICENSE-3RD-PARTY.md, LICENSE-SQLITE, NOTICE, COPYING... - not code files)
const noticeFile = /^(licen[cs]e|copying|notice|patents)([-_.][a-z0-9_.-]+)?$/i;
const codeFile = /\.(go|s|c|h)$/i;
const sections = [];
const add = (title, text) => sections.push(`${'='.repeat(79)}\n${title}\n${'='.repeat(79)}\n\n${text.trim()}\n`);

const goroot = go('env', 'GOROOT').trim();
add(`Go (the standard library and runtime) ${go('env', 'GOVERSION').trim()}`, readFileSync(join(goroot, 'LICENSE'), 'utf8'));

for (const [path, version, dir] of modules) {
  if (!dir || !existsSync(dir)) throw new Error(`${path}: not downloaded (run go mod download)`);
  const files = readdirSync(dir).filter((f) => noticeFile.test(f) && !codeFile.test(f)).sort();
  if (!files.length) throw new Error(`${path}: no license file found in ${dir}`);
  add(`${path} ${version}`, files.map((f) => readFileSync(join(dir, f), 'utf8').trim()).join('\n\n---\n\n'));
}

